"""Audit tidy model results before generating performance figures."""

from pathlib import Path

import pandas as pd

from analysis.model_results.model_data import load_results

OUTPUT_DIR = Path(__file__).parent / "outputs"
TRUNCATION_TOKENS = 4000


def write_data_quality_report(results: pd.DataFrame) -> None:
    """Write response-health tables and targeted follow-up findings."""
    required = {
        "riddle_id",
        "model_display",
        "generation_status",
        "answer_parse_status",
        "judge_verdict",
    }
    missing = required - set(results.columns)
    if missing:
        raise ValueError(
            f"Tidy model results are missing required columns: {sorted(missing)}"
        )
    summary = (
        results.groupby("model_display")
        .agg(
            rows=("riddle_id", "size"),
            riddles=("riddle_id", "nunique"),
            empty=("answer_parse_status", lambda values: int(values.eq("empty").sum())),
            unparsed=(
                "answer_parse_status",
                lambda values: int(values.eq("unparsed").sum()),
            ),
            truncated=(
                "output_tokens",
                lambda values: int(values.fillna(0).ge(TRUNCATION_TOKENS).sum()),
            ),
            missing_judge=("judge_verdict", lambda values: int(values.isna().sum())),
            generation_errors=(
                "generation_status",
                lambda values: int(~values.eq("success").sum()),
            ),
        )
        .reset_index()
    )
    summary["unextractable_rate"] = (summary["empty"] + summary["unparsed"]) / summary[
        "rows"
    ]
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    summary.to_csv(OUTPUT_DIR / "model_data_quality.csv", index=False)
    concerning = summary[summary["unextractable_rate"] > 0.05]
    lines = [
        "# Model-results data quality report",
        "",
        "Generated by `python -m analysis.model_results.data_audit`; do not edit by hand.",
        "",
        "## Required checks",
        "",
        f"- Models with complete 6,099-riddle coverage: {len(summary)}.",
        f"- Rows missing a deterministic judge verdict: {int(summary.missing_judge.sum())}.",
        f"- Generation errors: {int(summary.generation_errors.sum())}.",
        "",
        "## Follow-up queue",
        "",
    ]
    if concerning.empty:
        lines.append("- No model exceeds the 5% unextractable-response threshold.")
    else:
        lines.extend(
            f"- {row.model_display}: {row.unextractable_rate:.1%} empty or unparsed responses; inspect token limits and answer formatting."
            for row in concerning.itertuples()
        )
    lines.extend(
        [
            "",
            "## Interpretation policy",
            "",
            "- Search-enabled runs remain labelled separately from closed-book runs.",
            "- Unparsed responses are failed attempts; generation errors are reported as coverage.",
            "- Strict-match scores are diagnostic floors until human or LLM judging is complete.",
        ]
    )
    (OUTPUT_DIR / "model_data_quality_report.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )


def main() -> None:
    """Audit the current complete-coverage model-results frame."""
    write_data_quality_report(load_results())


if __name__ == "__main__":
    main()
