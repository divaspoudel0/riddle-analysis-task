"""Write auditable corpus summaries and targeted data-quality findings."""

import pandas as pd

from analysis.constants import RIDDLE_ANALYSIS_OUTPUT_DIR
from analysis.riddle_analysis.corpus_data import (
    load_corpus,
    plot_validation_coverage,
    save_tables,
)

OUTPUT_DIR = RIDDLE_ANALYSIS_OUTPUT_DIR


def write_quality_report(corpus: pd.DataFrame) -> None:
    """Write actionable corpus checks for data collection and repair work."""
    native_english = corpus["language_code"].eq("eng")
    missing_riddle = corpus["riddle_english"].isna() & ~native_english
    missing_answer = corpus["reference_answer_english"].isna() & ~native_english
    duplicate_english = (
        corpus.loc[corpus["riddle_english"].notna(), "riddle_english"]
        .duplicated(keep=False)
        .sum()
    )
    low_validation = (
        corpus.groupby("community")["human_answer_score"]
        .apply(lambda values: values.notna().mean())
        .sort_values()
        .head(10)
    )
    lines = [
        "# Corpus quality report",
        "",
        "Generated by `python -m analysis.riddle_analysis.corpus_audit`; do not edit by hand.",
        "",
        "## Release-blocking checks",
        "",
        f"- Duplicate riddle IDs: {int(corpus.riddle_id.duplicated().sum())}.",
        f"- Non-valid rows: {int((corpus.row_status != 'valid').sum())}.",
        f"- Communities not containing 100 riddles: {int((corpus.groupby('community').size() != 100).sum())}.",
        "",
        "## Targeted repair queue",
        "",
        f"- Missing English riddle translations: {int(missing_riddle.sum())}. Prioritize the affected source rows.",
        f"- Missing English reference answers: {int(missing_answer.sum())}. These prevent consistent English-side evaluation.",
        f"- English riddle rows participating in duplicate text: {int(duplicate_english)}. Review for legitimate repeated forms or accidental copies.",
        f"- Riddles without a recorded human answer score: {int(corpus.human_answer_score.isna().sum())}.",
        "",
        "## Lowest human-validation coverage by community",
        "",
        *[
            f"- {community}: {coverage:.0%}"
            for community, coverage in low_validation.items()
        ],
    ]
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUTPUT_DIR / "corpus_quality_report.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )


def main() -> None:
    """Regenerate corpus audit and collection summary tables."""
    corpus = load_corpus()
    save_tables(corpus)
    write_quality_report(corpus)
    plot_validation_coverage(corpus)


if __name__ == "__main__":
    main()
