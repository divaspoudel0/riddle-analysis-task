"""Write auditable corpus summaries and targeted data-quality findings."""

from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd

from analysis.constants import RUN_BATCH_ORDER, figure_stem
from analysis.riddle_analysis.corpus_data import load_corpus, save_tables
from analysis.style import PALETTE, acl_figure_size, apply_style, save_figure_pair

OUTPUT_DIR = Path(__file__).parent / "outputs"


def plot_validation_coverage(corpus: pd.DataFrame) -> None:
    """Audit and plot validator-name and answer-score coverage by round."""
    summary = (
        corpus.assign(
            has_validator=corpus.human_validator_name.notna(),
            has_score=corpus.human_answer_score.notna(),
        )
        .groupby("run_batch")[["has_validator", "has_score"]]
        .mean()
        .reindex(RUN_BATCH_ORDER)
        .mul(100)
    )
    apply_style()
    fig, ax = plt.subplots(figsize=acl_figure_size(1, 2.35))
    positions = range(len(summary))
    ax.plot(
        positions,
        summary["has_validator"],
        marker="o",
        color=PALETTE["blue"],
        label="Named validator",
    )
    ax.plot(
        positions,
        summary["has_score"],
        marker="o",
        color=PALETTE["vermillion"],
        label="Recorded answer score",
    )
    ax.set(
        xticks=list(positions),
        xticklabels=summary.index,
        ylim=(0, 100),
        ylabel="Riddles (%)",
        title="Human-validation metadata coverage",
    )
    ax.legend(loc="upper left", fontsize=7)
    fig.tight_layout()
    save_figure_pair(fig, figure_stem("riddle_analysis", "human_validation_coverage"))
    plt.close(fig)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    summary.reset_index(names="run_batch").to_csv(
        OUTPUT_DIR / "human_validation_coverage.csv", index=False
    )


def write_quality_report(corpus: pd.DataFrame) -> None:
    """Write actionable corpus checks for data collection and repair work."""
    native_english = corpus["community"].isin({"english_canada", "english_usa"})
    missing_riddle = corpus["riddle_english"].isna() & ~native_english
    missing_answer = corpus["reference_answer_english"].isna() & ~native_english
    duplicate_english = (
        corpus.loc[corpus["riddle_english"].notna(), "riddle_english"]
        .duplicated(keep=False)
        .sum()
    )
    low_validation = (
        corpus.groupby("community")["human_answer_score"]
        .apply(lambda values: values.notna().mean())
        .sort_values()
        .head(10)
    )
    lines = [
        "# Corpus quality report",
        "",
        "Generated by `python -m analysis.riddle_analysis.corpus_audit`; do not edit by hand.",
        "",
        "## Release-blocking checks",
        "",
        f"- Duplicate riddle IDs: {int(corpus.riddle_id.duplicated().sum())}.",
        f"- Non-valid rows: {int((corpus.row_status != 'valid').sum())}.",
        f"- Communities not containing 100 riddles: {int((corpus.groupby('community').size() != 100).sum())}.",
        "",
        "## Targeted repair queue",
        "",
        f"- Missing English riddle translations: {int(missing_riddle.sum())}. Prioritize the affected source rows.",
        f"- Missing English reference answers: {int(missing_answer.sum())}. These prevent consistent English-side evaluation.",
        f"- English riddle rows participating in duplicate text: {int(duplicate_english)}. Review for legitimate repeated forms or accidental copies.",
        f"- Riddles without a recorded human answer score: {int(corpus.human_answer_score.isna().sum())}.",
        "",
        "## Lowest human-validation coverage by community",
        "",
        *[
            f"- {community}: {coverage:.0%}"
            for community, coverage in low_validation.items()
        ],
    ]
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUTPUT_DIR / "corpus_quality_report.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )


def main() -> None:
    """Regenerate corpus audit and collection summary tables."""
    corpus = load_corpus()
    save_tables(corpus)
    write_quality_report(corpus)
    plot_validation_coverage(corpus)


if __name__ == "__main__":
    main()
